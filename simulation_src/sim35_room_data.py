#!/usr/bin/env python3
"""
sim35_room_data.py - the extra inputs Sim 3.5's configurable Room for homes tab needs. Runs no SWMM.

The page already loads Sim 3's region runs (simulation3/data/regions.js) and network (catchment.js),
which are what sim35_capacity.py reads, so the browser redoes that calculation itself
(simulation35/room_calc.js) for any limit, new-home load and timing. Only three things are not on the
page, and this script packs them into simulation35/data/room.js:

    loads      the new-home load defaults from config.js (people, litres a day, peak factor)
    timing     the projection cases and years, also from config.js
    suburb     Sim 3-e's 56 whole-suburb runs (results/sim3e/suburb.json): settled depth at every
               manhole, per case and build-out step, in the chamber order of simulation3/data/growth.js

    python sim35_room_data.py
"""
import json, os

import osp_config

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SUBURB = os.path.join(HERE, "results", "sim3e", "suburb.json")
GROWTH = os.path.join(ROOT, "simulation3", "data", "growth.js")
OUT = os.path.join(ROOT, "simulation35", "data", "room.js")


def chamber_names():
    s = open(GROWTH, encoding="utf-8").read()
    at = s.index('"chambers":')
    return json.loads(s[s.index("[", at):s.index("]", at) + 1])


def main():
    cfg = osp_config.load()
    loads, reg = cfg["loads"], cfg["simulation"]["regions"]
    tm = reg["timing"]
    ch = chamber_names()
    sub = json.load(open(SUBURB, encoding="utf-8"))
    suburb = {}
    for row in sorted(sub["rows"], key=lambda x: (x["case"], x["step"])):
        c = suburb.setdefault(row["case"], {"dw": [], "depth": []})
        depth = row["depth_mm"]
        missing = [n for n in ch if n.replace("MH", "") not in depth]
        if missing:
            raise SystemExit(f"STOP: suburb run {row['case']} step {row['step']} lacks {len(missing)} chambers")
        c["dw"].append(row["dwellings"])
        c["depth"].append([round(depth[n.replace("MH", "")], 1) for n in ch])
    steps = {len(c["dw"]) for c in suburb.values()}
    if steps != {len(reg["ladder"])}:
        raise SystemExit(f"STOP: suburb runs have {steps} steps, the ladder has {len(reg['ladder'])}")
    data = {
        "loads": {"people": loads["people_per_new_dwelling"], "litres": loads["litres_per_person_day"],
                  "peak": loads["peak_factor"]},
        "timing": {"high": reg["anchor_dwellings"], "medium": reg["anchor_medium_dwellings"],
                   "years": tm["projection_years"], "from": tm["growth_counted_from"],
                   "lag": tm["approval_to_connection_years"]},
        "suburb_anchor": sub["anchor_dwellings"],
        "suburb": suburb,
    }
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by simulation_src/sim35_room_data.py. Do not edit by hand.\n")
        f.write("window.SIM35_ROOM = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(suburb)} cases x {len(reg['ladder'])} steps x {len(ch)} manholes")


if __name__ == "__main__":
    main()
