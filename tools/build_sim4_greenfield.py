#!/usr/bin/env python3
"""Build the saved-run greenfield explorer payload; --check compares in memory."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'simulation_src/results/sim4/greenfield'
TARGET = ROOT / 'simulation4/data/greenfield.js'


def build():
    data = json.loads((SOURCE / 'eval.json').read_text())
    plan = json.loads((SOURCE / 'plan.json').read_text())
    text = (ROOT / 'simulation3/data/catchment.js').read_text()
    geo = json.loads(text[text.index('{'):text.rindex('}') + 1])
    nodes = {n['name']: n for n in geo['nodes']}
    eligible = {s['manhole_id']: s for s in plan['eligible']}
    for site in data['sites']:
        source = eligible[site['manhole_id']]
        if site['steps'] != source['steps']:
            raise ValueError('Plan changed; run sim4_greenfield_eval.py again')
        site.update({k: nodes[site['id']][k] for k in ('x', 'y')})
        site['headroom'] = source['headroom']
    return '// Generated by tools/build_sim4_greenfield.py. Do not edit by hand.\nwindow.SIM4_GREENFIELD = ' + json.dumps(data, separators=(',', ':'), allow_nan=False) + ';\n'


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    content = build()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != content:
            raise SystemExit('greenfield.js differs; rebuild with tools/build_sim4_greenfield.py')
        print('greenfield.js is current')
    else:
        TARGET.write_text(content)
        print('Wrote ' + str(TARGET.relative_to(ROOT)))


if __name__ == '__main__':
    main()
