#!/usr/bin/env python3
"""
build_sim3_regions.py - rebuild simulation3/data/regions.js (window.SIM3_REGIONS) from the infill runs.

The Sim 3 page's infill data was first written by a builder that never reached the repository.
This rebuilds the same file from what is committed: config.js (the case set and the region
partition), the per-case summary.json files written by sim3_regions.py, and the analysis.json
written by sim3_analysis.py. Manholes are stored as indices into simulation3/data/growth.js's
chamber list, which is what the Sim 3 and Sim 3.5 pages read.

    python tools/build_sim3_regions.py            # write simulation3/data/regions.js
    python tools/build_sim3_regions.py --check    # rebuild in memory, compare with the file, exit 1 if different
    python tools/build_sim3_regions.py --partition bisection --out <file>   # the equal-home regions, unpublished

Simulations 3, 3.5 and 4 publish the hand-picked (listed) regions from simulation3/data/regions.js. The equal-home
(bisection) regions have been run in SWMM but no page publishes them; --out writes them to a file of your choice.

The partition (config.js simulation.regions.partition, or --partition) picks which runs are read:
results/sim3/regions (listed) or results/sim3/regions_bisection (bisection).
"""
import argparse, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "simulation_src"))
os.chdir(os.path.join(ROOT, "simulation_src"))

import sim25          # noqa: E402
import sim25_grid     # noqa: E402
import sim3_regions   # noqa: E402

DATA = os.path.join(ROOT, "simulation3", "data")
HEADER = ("// Generated by tools/build_sim3_regions.py - do not edit by hand.\n"
          "// EPA SWMM output, quantised and base64 packed. The physics is SWMM's;\n"
          "// this file is only its saved answer.\n")
RULES = [("rise10", "r10"), ("rise25", "r25"), ("rise50", "r50"), ("alarm", "alarm"), ("surcharge", "surcharge")]


def read_js(path):
    t = open(path, encoding="utf-8").read()
    return json.loads(t[t.index("{"):t.rindex("}") + 1])


def case_meta():
    """tag -> (ii, label, note), in config.js's case order."""
    weather = {w["ii"]: w for w in sim25.CASE_CONFIG["weather"]}
    variants = (sim25.CASE_CONFIG.get("sensitivity") or {}).get("variants", [])
    out = {}
    for c in sim25_grid.cases("all"):
        w = weather[c.ii]
        label = w["label"]
        for v in variants:
            if all(getattr(c, k) == x for k, x in v["set"].items()):
                label += " + " + v["label"]
        out[c.tag()] = (c.ii, label, w["note"])
    return out


def build(out_dir):
    chambers = read_js(os.path.join(DATA, "growth.js"))["chambers"]
    ix = {int(m[2:]): i for i, m in enumerate(chambers)}
    I = lambda m: ix[int(m)]
    ids = lambda ms: [I(m) for m in ms]

    an = json.load(open(os.path.join(out_dir, "analysis.json"), encoding="utf-8"))
    meta = case_meta()
    tags = [t for t in meta if t in an["cases"]]
    summ = {t: json.load(open(os.path.join(out_dir, t, "summary.json"), encoding="utf-8")) for t in tags}
    first = summ[tags[0]]
    reg_ids = [r["id"] for r in an["regions"]]
    ladder = first["ladder"]

    regions = [{"id": r["id"], "name": r["name"], "exitPipe": r["exit_pipe"],
                "manholes": sorted(ids(r["manholes"])), "nManholes": r["n_manholes"],
                "dwellings": r["dwellings"], "lengthM": r["length_m"], "nominal": r["nominal_dwellings"],
                **({"overlay": True} if r.get("overlay") else {})}
               for r in an["regions"]]
    cases = [{"tag": t, "ii": meta[t][0], "label": meta[t][1], "note": meta[t][2],
              "settle": summ[t]["run_length"]} for t in tags]
    base = {t: {"alarm": sorted(ids(summ[t]["baseline"]["alarm"])),
                "surcharged": sorted(ids(summ[t]["baseline"]["surcharged"])),
                "spilled": sorted(ids(summ[t]["baseline"]["spilled"])),
                "depthMm": {str(I(m)): round(d * 1000) for m, d in summ[t]["baseline_depth_m"].items()},
                "pumps": summ[t]["baseline"]["pumps"]} for t in tags}
    rows = {t: [{"r": reg_ids.index(x["region"]), "s": ladder.index(x["step"]), "dw": x["dwellings"],
                 "lps": x["added_lps"], "alarm": sorted(ids(x["alarm"])), "sur": sorted(ids(x["surcharge"])),
                 "spill": sorted(ids(x["spilled"])),
                 "rise": [[I(m), v] for m, v in sorted(x["rise_mm"].items(), key=lambda kv: -kv[1])],
                 "pumps": x["pumps"], "run": x["run"]} for x in summ[t]["rows"]] for t in tags}

    def plan(p):
        return {"chosen": ids(p["chosen"]), "curve": p["curve"]}

    rules = {}
    for long, short in RULES:
        a = an["rules"][long]
        r = {"detectable": a["detectable"], "greedy": plan(a["greedy"]),
             "exact": [{**e, "chosen": ids(e["chosen"])} for e in a["exact"]],
             "loo": {t: {"chosen": ids(v["chosen"]), "score": v["score_on_held_out"]}
                     for t, v in a["leave_one_out"].items()},
             "firstSeen": {rid: {t: ([I(v[0])] + v[1:] if v else v) for t, v in byc.items()}
                           for rid, byc in a["first_detection_by_case"].items()}}
        if a.get("risk"):
            k = a["risk"]
            r["risk"] = {"greedy": plan(k["greedy"]),
                         "exact": [{"k": e["k"], "chosen": ids(e["chosen"]), "worst": e["worst"], "average": e["average"]}
                                   for e in k["exact"]],
                         **{kk: vv for kk, vv in k.items() if kk not in ("greedy", "exact")}}
        rules[short] = r

    out = {"anchor": first["anchor_dwellings"], "councilConnections": first["council_connections"],
           "ladder": ladder, "regions": regions, "cases": cases, "base": base, "rows": rows, "rules": rules,
           "timeRule": {t: {rid: {"best": None if v["best_candidate"] is None else I(v["best_candidate"]),
                                  "riseMm": v["rise_mm"], "days": v["days"]} for rid, v in byr.items()}
                        for t, byr in an["time_rule"].items()},
           "chokePoints": [{"i": I(c["manhole"]), "headroomMin": c["headroom_mm_min"],
                            "headroomMean": c["headroom_mm_mean"], "alarmCases": c["already_in_alarm_cases"],
                            "regionsSeen": c["n_regions_seen"]} for c in an["choke_points"]],
           "pumpIndicator": an["pump_indicator"], "wetWeatherOnly": an["wet_weather_only"],
           "runLength": an["run_length"],
           "riskWeights": {t: {f"{w['region']}|{w['step']}": {"w": w["w"], "O": w["O"], "S": w["S"],
                                                              "at": None if w["at"] is None else I(w["at"]),
                                                              "ddBefore": w["dd_before"], "ddAfter": w["dd_after"]}
                               for w in ws} for t, ws in an["risk"]["weights"].items()},
           "riskDefinition": an["risk"]["definition"]}
    return HEADER + "window.SIM3_REGIONS = " + json.dumps(out, separators=(",", ":"), ensure_ascii=False) + ";\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--partition", choices=sim3_regions.PARTITIONS,
                    help=f"override config.js regions.partition (now {sim3_regions.PARTITION})")
    ap.add_argument("--check", action="store_true", help="compare with the committed file instead of writing")
    ap.add_argument("--out", default=os.path.join("simulation3", "data", "regions.js"),
                    help="file to write or check, relative to the repository root (default simulation3/data/regions.js)")
    args = ap.parse_args()
    target = os.path.join(ROOT, args.out)
    out_dir = sim3_regions.out_dir(args.partition or sim3_regions.PARTITION)
    text = build(out_dir)
    if args.check:
        old = open(target, encoding="utf-8").read()
        strip = lambda s: s[s.index("window."):]
        same = strip(old) == strip(text)
        print(f"{os.path.relpath(target, ROOT)}: {'identical' if same else 'DIFFERENT'} to a rebuild from "
              f"{os.path.relpath(out_dir, ROOT)} (header line ignored)")
        sys.exit(0 if same else 1)
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", os.path.relpath(target, ROOT), f"from {os.path.relpath(out_dir, ROOT)}")


if __name__ == "__main__":
    main()
