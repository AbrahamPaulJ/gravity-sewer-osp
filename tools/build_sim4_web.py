def greenfield_joins():
    """(eligible, candidates): candidate manholes whose widest outgoing pipe is GF_MIN_MM or more, counted from the
    model (sim25.py, whole area), the same rule as the greenfield grid's. Takes about half a minute."""
    sys.path.insert(0, SRC)
    cwd = os.getcwd()
    try:
        os.chdir(SRC)
        import sim25
        probe = sim25.Sim25Model(sim25.Case(), whole=True, outlet_head=None)
    finally:
        os.chdir(cwd)
    widest = {}
    for p in probe.net.pipes:
        widest[p.up] = max(widest.get(p.up, 0.0), p.dia)
    cands = [probe.chambers[c] for c in probe.candidates]
    return sum(widest.get(n, 0.0) * 1000 >= GF_MIN_MM - 1e-6 for n in cands), len(cands)


def read_config(path=CONFIG):
    t = open(path, encoding="utf-8").read()
    at = t.index(".OSP_CONFIG =")
    return json.loads(t[t.index("{", at):t.rindex("}") + 1])


def source_const(script, name):
    """A constant as the script sets it (NAME = value at the start of a line), so the words follow the code."""
    t = open(os.path.join(SRC, script), encoding="utf-8").read()
    return float(re.search(rf"^{name} = ([0-9.]+)", t, re.M).group(1))


def band_cuts():
    """The capacity bands' cut-offs, read from sim35_capacity.py so the words follow the code."""
    t = open(os.path.join(SRC, "sim35_capacity.py"), encoding="utf-8").read()
    m = re.search(r"^BAND_HI, BAND_LO = ([0-9.]+), ([0-9.]+)", t, re.M)
    return float(m.group(1)), float(m.group(2))


def build(numbers, regions, handpicked=HANDPICKED, floats=FLOAT, greenfield=None):
    """(sim4.js text, redo.html text)."""
    nm, reg, fl = json.load(open(numbers, encoding="utf-8")), read_js(regions), json.load(open(floats, encoding="utf-8"))
    assert fl["scope"]["targets"] == nm["targets"], f"{floats} is for other regions: rerun sim4_float.py after sim4_numbers.py"
    lad1 = next(r for r in nm["ladder"] if r["k"] == 1)
    seed_k = next(f["1.0"] for f in nm["fewest"] if f["scope"] == "Design wet only")
    overlay = [r for r in reg["regions"] if r.get("overlay")]
    geo = read_js(os.path.join(ROOT, "simulation3", "data", "catchment.js"))
    hi, lo = band_cuts()
    ctx = {"seed": nm["ladder"][seed_k - 1]["chosen"] if seed_k else lad1["chosen"],
           "nwet": len(nm["universe"]), "pipes": geo["nPipes"], "manholes": len(read_js(os.path.join(ROOT, "simulation3", "data", "growth.js"))["chambers"]),
           "draws": int(source_const("sim4_numbers.py", "DRAWS")), "anchor": round(reg["anchor"]), "bisection": any("bisection" in r or r.get("overlay") for r in reg["regions"]),
           "nparts": len(reg["regions"]) - len(overlay), "overlay": [f"{r['id']}, the {r['name'].split(' (')[0]}" for r in overlay],
           "overlay_ids": [r["id"] for r in overlay], "float": fl,
           "handpicked": json.load(open(handpicked, encoding="utf-8")) if handpicked and os.path.exists(handpicked) else None,
           "capacity": json.load(open(CAPACITY, encoding="utf-8")), "loads": read_config()["loads"], "band_hi": hi, "band_lo": lo,
           "design_ii": f"{next(c['ii'] for c in reg['cases'] if c['tag'] == DESIGN_TAG):g}",
           "greenfield": greenfield or greenfield_joins()}
    k0, rec = len(ctx["seed"]), nm["recommend"]
    st = steps(nm, reg, ctx)
    N = notes(nm, reg, ctx)
    for s in st:
        s["notes"] = N[s["id"]]
    out = {"design": DESIGN_TAG, "steps": st,
           "popups": {str(k0): popups(nm, ctx, k0), str(rec): popups(nm, ctx, rec)},
           "triage": {i: v["action"] for i, v in nm["triage"].items()},
           "ladder": {str(k0): ctx["seed"], str(rec): next(r for r in nm["ladder"] if r["k"] == rec)["chosen"]},
           # What Explore needs to score on the story's test: the nested list, and the exact solver's own set at each
           # count on that test (10 mm rule), so its Exact optimum there is the story's, not the broader test's.
           "explore": {"ladder": [r["chosen"] for r in sorted(nm["ladder"], key=lambda r: r["k"])],
                       "exact": [r["exact_set"] for r in sorted(nm["ladder"], key=lambda r: r["k"])],
                       "targets": nm["targets"], "recommend": rec},
           "stepCount": 6}
    return (HEADER + "window.SIM4 = " + json.dumps(out, separators=(",", ":"), ensure_ascii=False) + ";\n",
            redo_page(nm, st, ctx))


def problems(text):
    """Em or en dashes, and words that must never be published."""
    out = [f"dash {c!r}" for c in ("—", "–") if c in text]
    out += [f"forbidden {m.group(0)!r}" for pat in FORBIDDEN for m in re.finditer(pat, text, re.I)]
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="compare with the files instead of writing")
    ap.add_argument("--numbers", default=NUMBERS, help="numbers.json (default simulation_src/results/sim4/numbers.json)")
    ap.add_argument("--regions", default=REGIONS, help="the regions file the page loads (default simulation4/data/regions.js)")
    ap.add_argument("--handpicked", default=HANDPICKED, help="the hand-picked regions' numbers, for the comparison (default results/sim4/numbers_handpicked.json; '' to leave it out)")
    ap.add_argument("--float", default=FLOAT, dest="floats", help="sim4_float.py's float.json, the same regions as --numbers (default results/sim4/float.json)")
    ap.add_argument("--out", default=TARGET, help="the data file to write or check (default simulation4/data/sim4.js)")
    ap.add_argument("--redo", default=REDO, help="the redo guide to write or check (default simulation4/redo.html)")
    args = ap.parse_args()
    data, redo = build(args.numbers, args.regions, args.handpicked, args.floats)
    bad = {os.path.basename(p): problems(t) for p, t in ((args.out, data), (args.redo, redo)) if problems(t)}
    if bad:
        sys.exit(f"REFUSING: {bad}")
    if args.check:
        diff = [p for p, t in ((args.out, data), (args.redo, redo)) if not os.path.exists(p) or open(p, encoding="utf-8").read() != t]
        for p in (args.out, args.redo):
            print(f"{os.path.relpath(p, ROOT)}: {'DIFFERENT' if p in diff else 'identical'} to a rebuild")
        sys.exit(1 if diff else 0)
    for p, t in ((args.out, data), (args.redo, redo)):
        with open(p, "w", encoding="utf-8", newline="\n") as f:
            f.write(t)
        print("wrote", os.path.relpath(p, ROOT))


if __name__ == "__main__":
    main()
