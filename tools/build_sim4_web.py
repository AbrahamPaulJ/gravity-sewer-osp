def esc(t):
    return html.escape(str(t), quote=False)


def figure(title, table_html, intro=""):
    """One block of 'Figures behind this step': a title, an optional line, and a table that scrolls inside itself."""
    return {"title": title, "intro": intro, "table": table_html}


