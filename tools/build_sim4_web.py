# ------------------------------------------------------------------------------------------------ build
def build(results, regions_path, greenfield=GREENFIELD):
    J = lambda name: json.load(open(os.path.join(results, name), encoding="utf-8"))
    reg = read_js(regions_path)
    warn, cap, mix, fc = J("warn.json"), J("capacity.json"), J("mix.json"), J("float_check.json")
    f = facts(reg, warn, cap, mix, fc)
    out = {
        "warn": warn,
        "capacity": {**{k: cap[k] for k in ("limits", "headline", "baseline_error", "draws")},
                     "areas": cap["bands"], "suburb": cap["whole_suburb_bands"]},
        "mix": {**{k: mix[k] for k in ("price", "margin", "budgets")}, **mix["tables"]},
        "wet": [c["tag"] for c in reg["cases"] if c["ii"] > 0],
        "design": DESIGN,
        "findings": findings(f),
        "assumptions": assumptions(f),
        "about": ABOUT,
        "sources": sources(f),
        "limits": limits(f),
        "floatCheck": fc,
        "coverage": {"rules": J("coverage.json")["rules"], "greenfield": json.load(open(greenfield, encoding="utf-8"))},
    }
    return HEADER + "window.SIM4 = " + json.dumps(out, separators=(",", ":"), ensure_ascii=False) + ";\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="compare with the committed file instead of writing")
    ap.add_argument("--results", default=RESULTS, help="the results folder (default simulation_src/results/sim4)")
    ap.add_argument("--regions", default=REGIONS, help="the regions file (default simulation4/data/regions.js)")
    ap.add_argument("--out", default=TARGET, help="the file to write or check (default simulation4/data/sim4.js)")
    args = ap.parse_args()
    text = build(args.results, args.regions)
    if args.check:
        same = open(args.out, encoding="utf-8").read() == text
        print(f"{os.path.relpath(args.out, ROOT)}: {'identical' if same else 'DIFFERENT'} to a rebuild")
        sys.exit(0 if same else 1)
    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote", os.path.relpath(args.out, ROOT))


if __name__ == "__main__":
    main()
