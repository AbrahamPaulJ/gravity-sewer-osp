def read_js(path):
    t = open(path, encoding="utf-8").read()
    return json.loads(t[t.index("{"):t.rindex("}") + 1])


def pct(x):
    return f"{x:.0%}"


def wa(w, a):
    return f"{pct(w)} / {pct(a)}"


def listing(xs):
    xs = list(xs)
    return xs[0] if len(xs) == 1 else ", ".join(xs[:-1]) + " and " + xs[-1] if xs else ""


def kdollars(v):
    return f"${v // 1000}k"


def table(head, rows):
    return ('<table class=""><thead><tr>' + "".join(f"<th>{h}</th>" for h in head) + "</tr></thead><tbody>" +
            "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows) + "</tbody></table>")


