#!/usr/bin/env python3
"""
build_sim4_web.py - write simulation4/data/sim4.js (window.SIM4), Simulation 4's six-step story, from
simulation_src/results/sim4/numbers.json (sim4_numbers.py) and the regions file the page loads.

Every number, region list and sensor note in the story, the popups and the Expert panel is read from those
files, so the words follow the runs. Given the hand-picked regions' numbers.json and simulation3/data/regions.js,
it reproduces the page as first published, except for two credits, which name no one here.

    python tools/build_sim4_web.py            # write simulation4/data/sim4.js
    python tools/build_sim4_web.py --check    # rebuild in memory, compare with the file, exit 1 if different

Run first, from simulation_src/:  SIM35_TARGET=sim4 python sim35_capacity.py && python sim4_numbers.py
"""
import argparse, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NUMBERS = os.path.join(ROOT, "simulation_src", "results", "sim4", "numbers.json")
REGIONS = os.path.join(ROOT, "simulation4", "data", "regions.js")
TARGET = os.path.join(ROOT, "simulation4", "data", "sim4.js")
HEADER = "// Generated by tools/build_sim4_web.py. Do not edit by hand.\n"
DESIGN_TAG = "ii0.11_flat_uniform_b1_sfree"
DESIGN = "Design wet"
GREENFIELD_SITES = (91, 328)      # manholes with a 225 mm+ outgoing main: Sim 3's greenfield join rule, no region changes it

# How each wet case reads in a sentence ("the only sensor here that sees ...").
CASE_PHRASE = {
    "Design wet": "a design wet day",
    "Beyond design": "a wetter day than design",
    "Severe": "severe wet weather",
    "Design wet + age-weighted I&I": "a design wet day where older pipes leak more (age-weighted)",
    "Design wet + outside inflow x1.5": "a design wet day with half as much again of outside inflow",
    "Beyond design + age-weighted I&I": "a wetter day than design where older pipes leak more (age-weighted)",
    "Beyond design + outside inflow x1.5": "a wetter day than design with half as much again of outside inflow",
}
WORDS = "zero one two three four five six seven eight nine ten".split()


def read_js(path):
    t = open(path, encoding="utf-8").read()
    return json.loads(t[t.index("{"):t.rindex("}") + 1])


def pct(x):
    return f"{x:.0%}"


def wa(w, a):
    return f"{pct(w)} / {pct(a)}"


def listing(xs):
    xs = list(xs)
    return xs[0] if len(xs) == 1 else ", ".join(xs[:-1]) + " and " + xs[-1] if xs else ""


def kdollars(v):
    return f"${v // 1000}k"


def table(head, rows):
    return ('<table class=""><thead><tr>' + "".join(f"<th>{h}</th>" for h in head) + "</tr></thead><tbody>" +
            "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows) + "</tbody></table>")


# ------------------------------------------------------------------------------------------------ the story
def steps(nm, reg, ctx):
    tri, lad, fb = nm["triage"], {r["k"]: r for r in nm["ladder"]}, nm["facts"]["before_growth"]
    seed, rec, price = ctx["seed"], nm["recommend"], nm["price"]["level"]
    by = lambda a: [i for i, v in tri.items() if v["action"] == a]
    d = fb[DESIGN]
    spill = "None spill." if not d["spilled"] else f"{d['spilled']} spill{'s' if d['spilled'] == 1 else ''}."
    s100 = reg["ladder"].index(1.0)
    rows = [x for x in reg["rows"][DESIGN_TAG] if x["s"] == s100]
    rises = {reg["regions"][x["r"]]["id"]: max([v for _, v in x["rise"]] or [0]) for x in rows}
    up = [r["id"] for r in reg["regions"] if rises.get(r["id"], 0) >= 10]
    flat = [r["id"] for r in reg["regions"] if rises.get(r["id"], 0) < 10]
    nsur = len({i for x in rows for i in x["sur"]})
    nspill = len({i for x in rows for i in x["spill"]})
    s3 = (f"Each region is built out on its own. {listing(up)} rise 10 mm or more; {listing(flat)} do not. "
          if up and flat else f"Each region is built out on its own. {'Every region rises' if up else 'No region rises'} 10 mm or more. ")
    s3 += ("At full build-out, no manhole newly surcharges and " if not nsur else
           f"At full build-out, {nsur} manhole{'' if nsur == 1 else 's'} newly surcharge{'s' if nsur == 1 else ''} and ")
    s3 += "none spills." if not nspill else f"{nspill} spill{'s' if nspill == 1 else ''}."
    leave_bands = {tri[i]["band"] for i in by("leave")}
    why_leave = "room left" if leave_bands <= {"room left"} else "already over before growth" if leave_bands <= {"already over"} else "room left, or already over before growth"
    parts = []
    if by("monitor"):
        parts.append(f"Monitor {listing(by('monitor'))}: likely to reach the pipe limit by 2041.")
    if by("watch"):
        parts.append(f"Watch {listing(by('watch'))}: could go either way.")
    if by("leave"):
        parts.append(f"Leave {listing(by('leave'))}: {why_leave}.")
    s4 = " ".join(parts) + " Not monitoring is a valid answer, if a design wet day is the right test."
    k0, nd = len(seed), nm["universe"][DESIGN]
    L0 = lad[k0]
    see = f"see{'s' if k0 == 1 else ''} all {nd}" if L0["design_wet"] >= 1 - 1e-9 else f"see{'s' if k0 == 1 else ''} {pct(L0['design_wet'])} of the {nd}"
    s5a = (f"{k0} sensor{'s' if k0 != 1 else ''} {see} growth runs in those regions on a design wet day. In other weather {'it falls' if k0 == 1 else 'they fall'} short: "
           f"{pct(L0['average'])} on average across {ctx['nwet']} wet cases. Click a sensor to see why it is there.")
    L5, wt = lad[rec], nm["warn_universe"]["target"]
    warned = f"all {wt}" if L5["warned_target"] == wt else f"{L5['warned_target']} of {wt}"
    h5 = next(h for h in nm["held_out"] if h["k"] == rec)
    s5b = (f"The same {k0} plus {rec - k0} more. Across {ctx['nwet']} wet cases they see {pct(L5['average'])} of growth runs on average "
           f"and {pct(L5['worst'])} in the worst case, and warn of {warned} overloads. On weather they were not chosen for: "
           f"{pct(h5['weather_runs'][0] / h5['weather_runs'][1])}.")
    s6 = (f"{kdollars(k0 * price)} or {kdollars(rec * price)}, at assumed prices. Real records of a normal day could confirm the design day "
          f"and save up to {rec - k0} sensors, about {kdollars((rec - k0) * price)}. A new suburb needs its own model runs: the method repeats, "
          f"this sensor list does not.")
    return [
        {"id": "1", "n": 1, "title": "The network", "map": "plain",
         "body": f"{ctx['pipes']} pipes and {ctx['manholes']} manholes, with new homes coming by 2041. The question is what data shows growth using up these pipes, and where to collect it."},
        {"id": "2", "n": 2, "title": "A design wet day, today", "map": "base", "legend": ["was"],
         "body": f"Before any new homes, the model has {d['surcharged']} manholes surcharged: water above the pipe top, the warning sign before an overflow. {spill} On a much wetter day it has {fb['Beyond design']['surcharged']}, so wet weather alone already matters."},
        {"id": "3", "n": 3, "title": "Add the 2041 homes", "map": "growth", "slider": True, "legend": ["was", "rise", "tip"], "body": s3},
        {"id": "4", "n": 4, "title": "Decide where to look", "map": "triage", "legend": ["monitor", "watch", "leave"], "body": s4},
        {"id": "5a", "n": 5, "title": "Place sensors, if the design day is right", "map": "sensors", "k": k0, "legend": ["sensor", "monitor", "watch"], "body": s5a},
        {"id": "5b", "n": 5, "title": "Place sensors, if the weather is unknown", "map": "sensors", "k": rec, "legend": ["sensor", "monitor", "watch"], "body": s5b},
        {"id": "6", "n": 6, "title": "Cost, and doing it again", "map": "sensors", "k": rec, "legend": ["sensor"], "body": s6},
    ]


# ------------------------------------------------------------------------------------------------ popups
def popups(nm, ctx, k):
    tri, lad, why = nm["triage"], {r["k"]: r for r in nm["ladder"]}, {r["manhole"]: r for r in nm["reasons"]}
    L = lad[k]
    out = []
    for n, m in enumerate(L["chosen"], 1):
        r, sw = why[m], nm["swaps"][str(k)][m]
        heard = [(g, v) for g, v in r["hears"].items() if v["first_step"]]
        if heard:
            listens = f"{listing([g for g, _ in heard])}, on a design wet day"
            g, v = min(heard, key=lambda x: x[1]["first_homes"])
            reacts = f"{v['first_homes']} new homes in {g} (+{v['first_rise']} mm)"
        else:
            wet = sorted(((g, len(v["cases_heard"])) for g, v in r["hears"].items() if v["cases_heard"]), key=lambda x: -x[1])[:2]
            listens = "In wetter weather only: " + ", ".join(f"{g} in {c} of {ctx['nwet']} wet cases" for g, c in wet)
            reacts = "Stays under 10 mm on a design wet day, even with all 2041 homes"
        if k == len(ctx["seed"]):
            lost = f"Design wet falls from {pct(L['design_wet'])} to {pct(sw['without_design'])} of growth runs"
        else:
            lost = f"Worst case falls from {pct(L['worst'])} to {pct(sw['without_worst'])}, average from {pct(L['average'])} to {pct(sw['without_average'])}"
        note = []
        home = r["home_regions"]
        if home and all(tri.get(h, {}).get("action") == "leave" for h in home):
            note.append(f"It sits in {listing(home)}, which need{'s' if len(home) == 1 else ''} no sensor of {'its' if len(home) == 1 else 'their'} own. It is here for flow passing through.")
        only = [c for c, v in L["per_case"].items() if v > 0 and sw["without_per_case"].get(c, 0) == 0]
        if only and k != len(ctx["seed"]):
            note.append(f"It is the only sensor here that sees {listing([CASE_PHRASE.get(c, c) for c in only])}.")
        if r["surcharged_before_growth"]:
            note.append("The model has this manhole surcharged before any growth. Worth a site check.")
        out.append({"name": m, "n": n, "listens": listens, "reacts": reacts, "lost": lost, "note": " ".join(note)})
    return out


# ------------------------------------------------------------------------------------------------ expert
def expert(nm, reg, ctx):
    tri, rec, wt = nm["triage"], nm["recommend"], nm["warn_universe"]["target"]
    letter = {"runs out": "O", "uncertain": "U", "room left": "R", "already over": "A"}
    span = lambda v: ("not reached" if v["homes_p10"] is None else
                      f"{v['homes_p10']} to {'beyond the top step' if v['homes_p90'] is None else v['homes_p90']}")
    region_note = ""
    if ctx["bisection"]:
        region_note = (f" Regions: {ctx['nparts']} holding near-equal numbers of existing homes, cut by the spatial bisection of Kim et al. (2022)"
                       + (f", plus {listing(ctx['overlay'])}, which overlaps them" if ctx["overlay"] else "") + ".")
    h = ["<h2>Which regions</h2>",
         "<p>Design wet, pipe limit 0.7 of bore (assumed). Runs out means monitor, uncertain means watch, room left means leave. "
         f"Bands by case: O runs out, U uncertain, R room left, A already over before growth.{region_note}</p>",
         table(["Region", "Action", "Band", "2041 homes", "Homes to limit, 10th to 90th", f"Band in the {ctx['nwet']} wet cases"],
               [[i, v["action"].capitalize(), v["band"], f"{v['homes_2041']:.0f}", span(v), " ".join(letter[b] for b in v["bands_by_case"].values())]
                for i, v in tri.items()])]
    tied = nm["tied_best_sets"]
    h += ["<h2>The ladder</h2>",
          f"<p>Each row adds one sensor to the row above. Target regions, build-out up to 100%, {ctx['nwet']} wet cases, 10 mm rule unless stated. "
          + (f"At least {tied} {WORDS[rec] if rec < len(WORDS) else rec}-sensor sets tie for best with the Design wet {'pair' if len(ctx['seed']) == 2 else 'set'}, so read this as one good choice, not the only one.</p>"
             if tied > 1 else f"No other {WORDS[rec]}-sensor set found ties with it.</p>"),
          table(["Sensors", "Added", "Worst / average", "Design wet", "25 mm rule", "Warned", "Exact solver, not nested", "Assumed cost"],
                [[r["k"], r["added"], wa(r["worst"], r["average"]), pct(r["design_wet"]), wa(r["worst_25"], r["average_25"]),
                  f"{r['warned_target']} of {wt}", wa(r["exact_worst"], r["exact_average"]), kdollars(r["cost"])] for r in nm["ladder"]])]
    sw = nm["swaps"][str(rec)]
    h += [f"<h2>Stand-ins for the {WORDS[rec] if rec < len(WORDS) else rec}</h2>",
          table(["Sensor", "Worst / average without it", "Warned without it", "Stand-ins with the same score", "Nearest"],
                [[m, wa(v["without_worst"], v["without_average"]), f"{v['without_warned']} of {wt}", v["stand_ins"],
                  ", ".join(a for a, _ in v["nearest_stand_ins"]) or "none"] for m, v in sw.items()])]
    ho = {x["k"]: x for x in nm["held_out"]}
    rnd = {x["k"]: x for x in nm["random"]}
    reg5, rand5 = ho[rec]["region_runs"][0] / ho[rec]["region_runs"][1], rnd[rec]["responsive"]["avg_mean"]
    transfer = ("the sensor list does not transfer, only the method" if reg5 - rand5 < 0.10
                else "the picks still beat random manholes on a region they were not chosen for")
    kmax = max(ho)
    blind = [c for c, v in nm["held_out_by_case"].items() if v[str(kmax)] == 0]
    blind_txt = (f" {listing([c.replace(DESIGN + ' + age-weighted I&I', 'Age-weighted Design wet') for c in blind])} cannot be predicted from the other weather: "
                 f"chosen without it, {kmax} sensors see 0% of it." if blind else "")
    h += ["<h2>How it holds up</h2>",
          f"<p>Chosen without the weather case or region tested, always exactly the stated number of sensors. Random is {ctx['draws']:,} draws on the same runs. "
          f"On an unseen region, {rec} sensors see {pct(reg5)} against {pct(rand5)} for random manholes that respond at all: {transfer}.{blind_txt}"
          + (f" {listing([o.split(',')[0] for o in ctx['overlay']])} shares its manholes with the regions it crosses, so holding it out does not hide it, and the unseen-region figure is a little generous."
             if ctx["overlay"] and any(o.split(",")[0] in nm["targets"] for o in ctx["overlay"]) else "") + "</p>",
          table(["Sensors", "Unseen weather", "Warned", "Unseen region", "Warned", "Random responsive, average", "Warned", "Random any, average", "Warned"],
                [[k, pct(x["weather_runs"][0] / x["weather_runs"][1]), f"{x['weather_warned'][0]} of {x['weather_warned'][1]}",
                  pct(x["region_runs"][0] / x["region_runs"][1]), f"{x['region_warned'][0]} of {x['region_warned'][1]}",
                  pct(rnd[k]["responsive"]["avg_mean"]), f"{rnd[k]['responsive']['warned_mean']:.1f}",
                  pct(rnd[k]["any"]["avg_mean"]), f"{rnd[k]['any']['warned_mean']:.1f}"] for k, x in sorted(ho.items())])]
    show = lambda v: "not reachable" if v is None else v
    h += ["<h2>Fewest sensors by weather covered</h2>",
          table(["Weather to cover", "80%", "90%", "100%"], [[f["scope"], show(f["0.8"]), show(f["0.9"]), show(f["1.0"])] for f in nm["fewest"]])]
    fx = nm["facts"]
    h += ["<h2>Where the model really overloads by 100%</h2>",
          f"<p>Manholes that newly surcharge or spill, any wet case. A surcharge is a warning sign, not an overflow: {fx['wet_rows_new_surcharge_by_100']} rows of "
          f"{fx['wet_rows_by_100']} show a new surcharge and {fx['wet_rows_new_spill_by_100']} a new spill.</p>",
          table(["Manhole", "Runs", "Spilling", "Weather cases", "Growth in", "Sits in"],
                [[o["manhole"], o["runs"], o["spill_runs"], len(o["cases"]), ", ".join(o["regions"]), ", ".join(o["home_regions"]) or "none"] for o in nm["overloads"]])]
    u = nm["universe"].values()
    keep = [i for i, v in tri.items() if v["action"] == "leave" and all(b == "room left" for b in v["bands_by_case"].values())]
    keeps = (f"{listing(keep)} alone keeps room in all {ctx['nwet']} wet cases." if len(keep) == 1 else
             f"Only {listing(keep)} keep room in all {ctx['nwet']} wet cases." if keep else f"No leave region keeps room in all {ctx['nwet']} wet cases.")
    anchor = [i for i, v in tri.items() if round(v["homes_2041"]) == ctx["anchor"]]
    homes = "Homes are per region, each built out on its own." + (
        f" {listing(anchor)}'s 2041 figure is the whole {ctx['anchor']}-home anchor by design, not a share of a total." if anchor else "")
    h += ["<h2>What limits this</h2>", "<ul>",
          "<li>No calibration: every figure is a model result, a guide to where to look first. No field data was available.</li>",
          "<li>The 10 mm and 25 mm rules, the pipe limit, the bands and both prices are assumed.</li>",
          f"<li>One simulated run moves a weather case's score by {round(100 / max(u))} to {round(100 / min(u))} points. Read smaller differences as noise.</li>",
          f"<li>Leave depends on Design wet. {keeps}</li>",
          f"<li>{homes}</li>",
          "<li>Sensors never fail here. Long-term sensor losses are not modelled.</li>",
          "</ul>",
          "<h2>What a new suburb must supply (draft)</h2>", "<ul>",
          "<li>Pipes and manholes: positions, inverts, diameters, lids.</li>",
          "<li>Its outlet and exit pipes, and how water leaves the modelled area.</li>",
          "<li>Homes now and projected, and how the suburb is divided into regions.</li>",
          "<li>Where homes connect, and pump stations with their rates.</li>",
          "<li>The weather cases and inflow rates to test.</li>",
          "<li>The pipe limit, the rise rule and sensor prices, ideally the utility's own.</li>",
          "<li>For a greenfield estate, where it may join: here, a main of 225 mm or more.</li>",
          "</ul>",
          "<h2>Greenfield</h2>",
          "<p>Not fully analysed. Four of its eight weather cases are not settled runs, and it has no warning or room analysis. It stays out of the story. Its coverage curve is in the earlier tool below.</p>",
          f"<p>Where a new estate could join: at a manhole whose widest outgoing pipe is 225 mm or more, {GREENFIELD_SITES[0]} of the {GREENFIELD_SITES[1]} candidate manholes here. "
          "An estate lays its own pipes and joins a trunk main, not a street sewer. The rule is a team member's proposal. It is a team assumption, not a utility standard, "
          "and whether that main has room for a given estate is a separate check.</p>",
          "<h2>Earlier tool</h2>",
          '<p><a href="../simulation35/index.html">Sim 3.5</a> keeps every control and table from the 6 November demo. Its five-sensor sets predate this ladder, '
          + ("it uses the hand-picked regions, " if ctx["bisection"] else "")
          + "and it covers all 8 regions and the stress steps, so its figures differ.</p>",
          "<p>The map's wheel zoom is from the team's buildings demo.</p>", ""]
    return "\n".join(h)


# ------------------------------------------------------------------------------------------------ build
def build(numbers, regions):
    nm, reg = json.load(open(numbers, encoding="utf-8")), read_js(regions)
    lad1 = next(r for r in nm["ladder"] if r["k"] == 1)
    seed_k = next(f["1.0"] for f in nm["fewest"] if f["scope"] == "Design wet only")
    overlay = [r for r in reg["regions"] if r.get("overlay")]
    ctx = {"seed": nm["ladder"][seed_k - 1]["chosen"] if seed_k else lad1["chosen"],
           "nwet": len(nm["universe"]), "pipes": 890, "manholes": len(read_js(os.path.join(ROOT, "simulation3", "data", "growth.js"))["chambers"]),
           "draws": 5000, "anchor": round(reg["anchor"]), "bisection": any("bisection" in r or r.get("overlay") for r in reg["regions"]),
           "nparts": len(reg["regions"]) - len(overlay), "overlay": [f"{r['id']}, the {r['name'].split(' (')[0]}" for r in overlay]}
    k0, rec = len(ctx["seed"]), nm["recommend"]
    out = {"design": DESIGN_TAG, "steps": steps(nm, reg, ctx),
           "popups": {str(k0): popups(nm, ctx, k0), str(rec): popups(nm, ctx, rec)},
           "triage": {i: v["action"] for i, v in nm["triage"].items()},
           "ladder": {str(k0): ctx["seed"], str(rec): next(r for r in nm["ladder"] if r["k"] == rec)["chosen"]},
           "expert": expert(nm, reg, ctx), "stepCount": 6}
    return HEADER + "window.SIM4 = " + json.dumps(out, separators=(",", ":"), ensure_ascii=False) + ";\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="compare with the file instead of writing")
    ap.add_argument("--numbers", default=NUMBERS, help="numbers.json (default simulation_src/results/sim4/numbers.json)")
    ap.add_argument("--regions", default=REGIONS, help="the regions file the page loads (default simulation4/data/regions.js)")
    ap.add_argument("--out", default=TARGET, help="the file to write or check (default simulation4/data/sim4.js)")
    args = ap.parse_args()
    text = build(args.numbers, args.regions)
    if args.check:
        same = open(args.out, encoding="utf-8").read() == text
        print(f"{os.path.relpath(args.out, ROOT)}: {'identical' if same else 'DIFFERENT'} to a rebuild")
        sys.exit(0 if same else 1)
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", os.path.relpath(args.out, ROOT))


if __name__ == "__main__":
    main()
